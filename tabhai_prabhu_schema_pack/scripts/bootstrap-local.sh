#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PROJECT_DIR="${1:-$PWD/tabhai-prabhu-local}"

need() { command -v "$1" >/dev/null 2>&1 || { echo "Missing required command: $1" >&2; exit 2; }; }
need supabase
need docker
need psql

if ! docker info >/dev/null 2>&1; then
  echo "Docker is installed but not running. Start Docker Desktop, then rerun." >&2
  exit 2
fi

mkdir -p "$PROJECT_DIR"
cd "$PROJECT_DIR"
if [[ ! -f supabase/config.toml ]]; then
  supabase init
fi

supabase migration new scripture_knowledge_base
MIGRATION="$(find supabase/migrations -maxdepth 1 -type f -name '*_scripture_knowledge_base.sql' -print | sort | tail -n 1)"
if [[ -z "$MIGRATION" ]]; then
  echo "Could not locate the migration file generated by Supabase CLI." >&2
  exit 3
fi

cat "$ROOT/001_scripture_schema_draft.sql" > "$MIGRATION"
printf '\n' >> "$MIGRATION"
cat "$ROOT/002_search_indexes_draft.sql" >> "$MIGRATION"
printf '\n' >> "$MIGRATION"
cat "$ROOT/004_seed_work_catalog_draft.sql" >> "$MIGRATION"

supabase start
supabase db reset
supabase status -o env > .env.local.supabase
chmod 600 .env.local.supabase
set -a
source .env.local.supabase
set +a
if [[ -z "${DB_URL:-}" ]]; then
  echo "DB_URL was not returned by 'supabase status -o env'. Check your CLI version." >&2
  exit 4
fi
psql "$DB_URL" -v ON_ERROR_STOP=1 -f "$ROOT/003_schema_invariants_test.sql"

echo "LOCAL SCRIPTURE DATABASE READY. No production project was contacted."
echo "Project directory: $PROJECT_DIR"
echo "Local credentials are in $PROJECT_DIR/.env.local.supabase (do not share or commit)."
